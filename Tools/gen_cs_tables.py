#!/usr/bin/env python3
"""
Writes Source/ArabicAutoTranslation/Arabic/Core/ArabicTables.cs from the same builders arabic_ref.py uses
(ar_tables.py, derived from Python's `unicodedata`). Re-run after changing ar_tables.py:

    python3 Tools/gen_cs_tables.py
"""
import hashlib
import os
import sys

import ar_tables as T

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'Source', 'ArabicAutoTranslation', 'Arabic', 'Core', 'ArabicTables.cs')


def fmt_ints(values, per_line=12, indent='            '):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append(indent + ', '.join('0x%X' % v if v > 9 else str(v) for v in chunk))
    return ',\n'.join(lines)


def flat(rows):
    out = []
    for r in rows:
        out.extend(r)
    return out


def main():
    bidi = flat(T.build_bidi_ranges())
    mirror_map = T.build_mirror_pairs()
    mirror = flat(sorted(mirror_map.items()))
    brackets = flat(sorted(T.build_bracket_pairs().items()))
    marks = flat(T.build_mark_ranges())
    joins = flat(T.build_join_table())
    forms = flat(T.build_form_rows())
    lamalef = flat(T.build_lamalef_rows())
    unshape = flat(T.build_unshape_pairs())
    unshape_lam = flat(T.build_unshape_lamalef())

    digest = hashlib.sha256()
    for arr in (bidi, mirror, brackets, marks, joins, forms, lamalef, unshape, unshape_lam):
        digest.update((','.join(str(v) for v in arr) + ';').encode('ascii'))
    sig = digest.hexdigest()[:16]

    parts = []
    parts.append('''// <auto-generated>
// Generated by Tools/gen_cs_tables.py from Python's `unicodedata` (Unicode %s). DO NOT EDIT BY HAND:
// change Tools/ar_tables.py and regenerate. The Python reference engine uses the very same tables.
// </auto-generated>
namespace ArabicAutoTranslation.Arabic
{
    /// <summary>Static Unicode data for the Arabic display engine (no runtime dependency on the platform's Unicode tables).</summary>
    internal static class ArabicTables
    {
        /// <summary>Unicode version the tables were generated from.</summary>
        internal const string UnicodeVersion = "%s";

        /// <summary>Content hash of every table below (part of the shaping / BiDi version identifiers).</summary>
        internal const string DataSignature = "%s";
''' % (T.UNICODE_VERSION, T.UNICODE_VERSION, sig))

    def emit(name, doc, arr):
        parts.append('        /// <summary>%s</summary>\n' % doc)
        parts.append('        internal static readonly int[] %s = new int[]\n        {\n%s\n        };\n\n' % (name, fmt_ints(arr)))

    emit('BidiRanges', 'Triplets (first, last, BidiClass id) for every code point range whose bidi class is not L.', bidi)
    emit('MirrorPairs', 'Pairs (code point, mirrored code point) - Bidi_Mirrored characters with a mirrored partner.', mirror)
    emit('BracketPairs', 'Pairs (opening bracket, closing bracket) used by the paired-bracket rule N0.', brackets)
    emit('MarkRanges', 'Pairs (first, last) of Mn / Me code points (cluster extenders).', marks)
    emit('JoinTable', 'Pairs (code point, joining type id) - 1=D 2=R 3=L 4=C 5=T; absent means U.', joins)
    emit('FormRows', 'Rows of five (base, isolated, final, initial, medial); 0 = no such form.', forms)
    emit('LamAlefRows', 'Rows of three (alef, isolated ligature, final ligature) for LAM + ALEF.', lamalef)
    emit('UnshapePairs', 'Pairs (presentation form, base letter) for single-letter presentation forms.', unshape)
    emit('UnshapeLamAlef', 'Pairs (lam-alef ligature, alef) for the LAM + ALEF ligature presentation forms.', unshape_lam)

    parts.append('    }\n}\n')
    text = ''.join(parts).replace('\r\n', '\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.normpath(OUT), 'signature', sig, 'bytes', len(text.encode('utf-8')))


if __name__ == '__main__':
    sys.exit(main())
